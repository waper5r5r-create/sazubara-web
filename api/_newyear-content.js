function letter(day, dayZhi, weak, index) {
  const [gan, zhi] = MONTHS[index], ss = shishen(day, gan), rel = zhiRelation(dayZhi, zhi), area = AREA[ss];
  const v = index === 10 || index === 11 ? 1 : (index === 0 || index === 1 ? 0 : (index % 2));
  const helped = !!weak && (ganWx(gan) === weak || ZHI_WX[zhi] === weak);
  const score = SS_SCORE[ss] + ZHI_SCORE[rel] + (helped ? 1 : 0);
  return {
    month: index + 1,
    seal: 'm' + String(index + 1).padStart(2, '0'),
    scene: SCENE[index],
    pillar: GAN_KR[gan] + ZHI_KR[zhi],
    ss: SS_NAME[ss],
    title: area.title[v],
    opening: OPENING[index],
    note: [MONTH_ZHI[rel], helped ? WEAK_LINE[weak] : ''].filter(Boolean),
    love: area.love[v], money: area.money[v], work: area.work[v], health: area.health[v],
    tip: area.tip[v],
    mood: score >= 3 ? 'cheer' : score >= 1 ? 'smile' : score === 0 ? 'shy' : 'worry',
    score
  };
}

// 내 사주로 조합한 편지. 잘못된 입력이면 null.
function compose(input) {
  const {gan, zhi} = input || {};
  if (typeof gan !== 'string' || gan.length !== 1 || !GAN.includes(gan) || typeof zhi !== 'string' || !ZHI_KR[zhi]) return null;
  const weak = WX_ORDER.includes(input.weak) ? input.weak : '';
  const letters = MONTHS.map((_, i) => letter(gan, zhi, weak, i));
  const ranked = letters.slice().sort((a, b) => b.score - a.score || a.month - b.month);
  const yearSs = shishen(gan, YEAR.gan), yearRel = zhiRelation(zhi, YEAR.zhi), year = YEAR_TEXT[yearSs];
  return {
    free: {
      year: {ss: SS_NAME[yearSs], title: year.title, keyword: year.keyword, body: year.body.concat(YEAR_ZHI[yearRel]), dayGan: GAN_KR[gan] + ganWx(gan)},
      best: ranked.slice(0, 3).map(l => l.month).sort((a, b) => a - b),
      watch: ranked[ranked.length - 1].month,
      letter: letters[0],
      teasers: letters.slice(1).map(l => ({month: l.month, seal: l.seal, title: l.title}))
    },
    paid: {letters: letters.slice(1)}
  };
}

