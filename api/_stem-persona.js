// 다섯 기운별 행동 문장은 양간(갑·병·경 등)에 맞춰 쓰여서, 을·정·임과 부딪혔다.
// 을은 토, 정은 수의 행동 문장이 성향에 맞아 빌려 쓰고, 맞지 않는 문장과 임은 따로 쓴다.
const clone = o => JSON.parse(JSON.stringify(o));
const strip = v => {
  if (typeof v === 'string') return v.replace(/[목화토금수] 기운(의|이 바탕인) 당신은/g, '당신은').replace(/[목화토금수] 기운은 [^.,]*기운이라, /g, '');
  if (Array.isArray(v)) return v.map(strip);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, strip(x)]));
  return v;
};
const scenes = (base, rows, key) => clone(base).map((s, i) => rows[i] ? {...s, pattern:rows[i][0], [key]:rows[i][1]} : s);
function fill(map, own) {
  map['을'] = strip(clone(map['토']));
  map['정'] = strip(clone(map['수']));
  if (own['을']) map['을'] = own['을'];
  if (own['정']) map['정'] = own['정'];
  map['임'] = own['임'];
}

